<?php

// 仕様：
// 1. for 文を二重に使用して、1の段から9の段までの九九表を計算してください。
// 2. ただし、計算結果を表示する際に以下の条件を追加してください。

// 計算結果が「奇数」の場合のみ画面に表示してください。
// 計算結果が「偶数」の場合は、数値の代わりに [E] という文字列を表示してください。
// 各段の終わりには改行を入れて、表形式で見やすく整形してください。

// 期待される出力のイメージ：
// 1 [E] 3 [E] 5 [E] 7 [E] 9
// [E] [E] [E] [E] [E] [E] [E] [E] [E]
// 3 [E] 9 [E] 15 [E] 21 [E] 27
// ...（以下9の段まで続く）

for ($i = 1; $i <= 9; $i++) {
    for ($j = 1; $j <= 9; $j++) {
        if (($i * $j) % 2 === 1) {
            echo $i * $j . ' ';
        } else {
            echo '[E] ';
        }
    }
    echo "\n";
}

?>